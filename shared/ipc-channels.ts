// ---------------------------------------------------------------------------
// Runtime channel registries
//
// `satisfies Record<Channel, true>` makes the compiler reject both a missing
// and an unknown channel, so these lists always match shared/ipc-contract.ts
// exactly. Tests use them to prove that the preload exposes, and the main
// process registers, every contract channel and nothing else.
// ---------------------------------------------------------------------------

function channelList<C extends string>(channels: Record<C, true>): readonly C[] {
  return Object.keys(channels) as C[]
}

